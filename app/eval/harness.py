"""Run evaluation cases through the pipeline and collect metrics (P4.1).

A case is a resume + JD (+ optional golden parse). Committed cases live in
data/eval/cases.json and use anonymized fixtures; private cases (the user's
real resume) live in data/eval/private/cases.json, which is gitignored.

Offline mode (default) uses no LLM, so its numbers are reproducible and
cheap: parsing, heuristic JD analysis, matching and scoring. --live uses the
configured provider (Groq free tier) and adds rewrite / suggestion metrics
and LLM cost when --tailor is given.
"""
import json
import logging
import os
import re
import tempfile
import time
from collections import Counter
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Dict, List, Optional

from app.analysis.jd_analyzer import JDAnalyzer
from app.eval.golden import golden_mismatches, project_resume

logger = logging.getLogger(__name__)

COMMITTED_MANIFEST = "data/eval/cases.json"
# Generated by scripts/make_eval_cases.py (P4.2), each with an expected.json.
GENERATED_MANIFEST = "data/eval/cases/manifest.json"
# Non-tech, non-US and non-English personas from the 2026-10-02 user test (P8.1).
PERSONA_MANIFEST = "data/eval/personas/manifest.json"
PRIVATE_MANIFEST = "data/eval/private/cases.json"


@dataclass
class Case:
    name: str
    resume: str
    jd: str
    golden: Optional[str] = None
    expected: Optional[str] = None  # expected.json with facts the run must reproduce (P4.2)
    private: bool = False
    # Which manifest the case came from: "fixture", "generated", "persona" or "private".
    suite: str = "fixture"


class OfflineLLM:
    """Stands in for LLMClient when no model should be called: every
    component sees "unavailable" and takes its deterministic path."""
    provider = "offline"
    model = None
    last_error = "offline evaluation (no LLM)"

    def is_available(self, refresh: bool = False) -> bool:
        return False

    def get_usage_summary(self) -> Dict:
        return {"provider": "offline", "model": None, "call_count": 0, "success_count": 0,
                "failure_count": 0, "total_prompt_tokens": 0, "total_completion_tokens": 0,
                "total_tokens": 0, "total_duration_seconds": 0.0}


class _RetryCounter(logging.Handler):
    def __init__(self):
        super().__init__(level=logging.WARNING)
        self.count = 0

    def emit(self, record):
        if "429" in record.getMessage():
            self.count += 1


def load_cases(include_private: bool = True, include_personas: bool = False) -> List[Case]:
    cases: List[Case] = []
    manifests = [(COMMITTED_MANIFEST, "fixture"), (GENERATED_MANIFEST, "generated")]
    if include_personas:
        manifests.append((PERSONA_MANIFEST, "persona"))
    if include_private:
        manifests.append((PRIVATE_MANIFEST, "private"))
    for path, suite in manifests:
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as f:
            for item in json.load(f):
                case = Case(private=suite == "private", suite=suite, **item)
                if os.path.exists(case.resume) and os.path.exists(case.jd):
                    cases.append(case)
                else:
                    logger.warning("Skipping case %s: input file missing", case.name)
    return cases


def keyword_coverage(keywords: List[str], resume_text: str) -> Dict:
    """Share of the JD's keywords found verbatim (whole term, any case) in
    the resume text. A plain measure that doesn't depend on the matcher."""
    found = [k for k in keywords if JDAnalyzer.count_occurrences(k, resume_text) > 0]
    missing = [k for k in keywords if k not in found]
    pct = round(100.0 * len(found) / len(keywords), 1) if keywords else None
    return {"pct": pct, "found": len(found), "total": len(keywords), "missing": missing}


def run_case(case: Case, *, live: bool = False, tailor: bool = False, out_dir: Optional[str] = None,
             judge: bool = False) -> Dict:
    from app.llm.client import LLMClient
    from app.services.tailor import TailorService

    llm = LLMClient() if live else OfflineLLM()
    service = TailorService(llm_client=llm, keep_run=False)  # outputs go to --out-dir; no copies in data/runs (P9.8)
    counter = _RetryCounter()
    logging.getLogger("app.llm.client").addHandler(counter)
    started = time.time()
    try:
        with open(case.jd, encoding="utf-8") as f:
            jd_text = f.read()
        parsed = service.parse_resume(case.resume)
        raw_doc, resume_doc, evidence = parsed
        resume = resume_doc.resume
        metrics: Dict = {"private": case.private}

        parse = {
            "issues": list(service.last_parse_issues),
            "experience": len(resume.experience),
            "roles": sum(len(e.all_roles()) for e in resume.experience),
            "bullets": sum(len(e.bullets) for e in resume.experience) + sum(len(p.bullets) for p in resume.projects),
            "skills": sum(len(v) for v in resume.skills.values()),
        }
        if case.golden and os.path.exists(case.golden):
            with open(case.golden, encoding="utf-8") as f:
                mismatches = golden_mismatches(project_resume(resume), json.load(f))
            parse["golden"] = "match" if not mismatches else "mismatch"
            parse["golden_mismatches"] = mismatches
        metrics["parse"] = parse

        # With --tailor, use the JD analysis generate_proposals makes (as the
        # UI does), so the metrics and the tailored output share one analysis
        # and the run makes exactly the pipeline's LLM calls.
        generated = service.generate_proposals(case.resume, jd_text, parsed=parsed) if tailor else None
        job = generated["job_description"] if generated else service.jd_analyzer.analyze(
            service.safety_guard.sanitize(jd_text))
        metrics["jd"] = {
            "source": job.analysis_source, "title": job.job_title, "company": job.company,
            "seniority": job.seniority, "years": [job.min_years, job.max_years],
            "requirements": len(job.requirements),
            "preferred": sum(r.priority == "preferred" for r in job.requirements),
            "keywords": len(job.keywords),
        }

        matches = service.matcher.match(job, evidence)
        matches = service.semantic_matcher.match(job.requirements, evidence, matches)
        from app.analysis.keyword_match import reconcile
        matches = reconcile(matches, service.keyword_matcher.match(job, resume))
        keyword_report = service.keyword_matcher.match(job, resume)
        metrics["match"] = {
            "score": keyword_report.rate,  # headline: keyword match rate (P1.2)
            "evidence_score": round(service.scorer.calculate_score(matches, job.requirements), 1),
            "statuses": dict(Counter(m.status for m in matches)),
            "keywords_matched": len(keyword_report.matched),
            "keywords_missing": [r.keyword for r in keyword_report.missing],
            "keyword_coverage": keyword_coverage(job.keywords, raw_doc.raw_text),
            "attainable_coverage": attainable_coverage(job.keywords, raw_doc.raw_text, keyword_report, jd_text),
        }

        tailored = None
        if tailor:
            from app.analysis.experience import years_of_experience, years_phrase
            # The summary's "4+ years" is computed from the role dates (P1.5),
            # so it counts as coming from the resume.
            source = f"{raw_doc.raw_text}\n{years_phrase(years_of_experience(resume)) or ''}"
            metrics["tailor"], tailored = _tailor_metrics(service, case, jd_text, parsed, generated, out_dir,
                                                          source_text=source, job=job)
            if judge:
                metrics["tailor"]["judge"] = _judge(jd_text, raw_doc.raw_text, _docx_text(tailored.get("docx")))

        if case.expected and os.path.exists(case.expected):
            with open(case.expected, encoding="utf-8") as f:
                failed = check_expected(json.load(f), resume, job, keyword_report, metrics,
                                        output_text=_docx_text((tailored or {}).get("docx")) if tailored else None)
            metrics["expected"] = {"failed": failed, "ok": not failed}

        usage = llm.get_usage_summary()
        metrics["llm"] = {
            "calls": usage.get("call_count", 0), "failures": usage.get("failure_count", 0),
            "tokens": usage.get("total_tokens", 0),
            "llm_seconds": round(usage.get("total_duration_seconds") or 0.0, 1),
            "retries_429": counter.count,
        }
        metrics["elapsed_s"] = round(time.time() - started, 1)
        return metrics
    finally:
        logging.getLogger("app.llm.client").removeHandler(counter)


def _tailor_metrics(service, case: Case, jd_text: str, parsed, generated: Dict, out_dir: Optional[str],
                    source_text: str = "", job=None):
    proposals = generated["proposals"]
    # As the review screen starts: fact-check failures and opt-in proposals unticked.
    approved = [p.model_dump() for p in proposals
                if getattr(p, "validation", None) != "REJECT" and not getattr(p, "opt_in", False)]
    case_dir = os.path.join(out_dir or tempfile.mkdtemp(prefix="eval_"), case.name)
    os.makedirs(case_dir, exist_ok=True)
    result = service.tailor_resume(
        case.resume, jd_text, case_dir, mode="ATS_DEFAULT", preapproved_proposals=approved,
        proposal_usage=generated.get("llm_usage"), parsed=parsed, job_desc=generated.get("job_description"),
    )
    pages = None
    if result.get("pdf") and os.path.exists(result["pdf"]):
        import pymupdf
        with pymupdf.open(result["pdf"]) as pdf:
            pages = pdf.page_count
    output_text = _docx_text(result.get("docx"))
    rate_after = float(result.get("alignment_score") or 0.0)
    return {
        "proposals": len(proposals),
        "changed": sum(1 for p in proposals if (p.proposed_text or "").strip() != (p.original_text or "").strip()),
        "statuses": dict(Counter(getattr(p, "status", None) or "none" for p in proposals)),
        "verdicts": dict(Counter(getattr(p, "validation", None) or "none" for p in proposals)),
        "gap_questions": len(generated["gap_questions"]),
        "score_after": float(result.get("alignment_score") or 0.0),
        "pages": pages,
        "target_pages": result.get("target_pages"),
        # P2.5: problems found re-parsing the rendered DOCX / PDF (0 = passes)
        "ats_round_trip": [w for w in result.get("warnings", []) if w.startswith("ATS round-trip")],
        # P2.6: content checks on the rendered resume, counted per check
        "content_lint": dict(Counter(i.check for i in result["content_lint"].issues)) if result.get("content_lint") else {},
        "metric_share": round(result["content_lint"].metric_share, 2) if result.get("content_lint") else None,
        # P4.2: numbers in the output that the resume never had (zero is the goal)
        "fabricated_numbers": fabricated_numbers(output_text, source_text),
        # P8.2: source lines that never reached the output (zero is the goal)
        "coverage": result.get("coverage"),
        # P4.2: keyword stuffing: above the target band, or a JD keyword repeated too often
        "stuffing": stuffing(output_text, job.keywords if job else [], rate_after,
                             float(result.get("initial_alignment_score") or 0.0)),
        "output_dir": case_dir,
    }, result


def attainable_coverage(keywords: List[str], resume_text: str, keyword_report, jd_text: str = "") -> Dict:
    """Of the JD keywords written verbatim somewhere in the resume, the share
    the keyword matcher finds (P4.2). Below 100% means the matcher misses
    something the resume plainly says; the target is at least 95%."""
    from app.analysis.keyword_match import is_place, tokens

    # A place the JD names ("Arizona") is not a skill: the matcher skips it (P8.17), so it isn't attainable (P9.15).
    attainable = [k for k in keywords if JDAnalyzer.count_occurrences(k, resume_text) > 0 and not is_place(k, jd_text)]
    # Compared as alias-canonical tokens: "machine learning" is the matcher's "ML" row.
    found_rows = {" ".join(tokens(r.keyword)) for r in keyword_report.rows if r.found}
    missed = [k for k in attainable if " ".join(tokens(k)) not in found_rows]
    pct = round(100.0 * (len(attainable) - len(missed)) / len(attainable), 1) if attainable else None
    return {"pct": pct, "attainable": len(attainable), "missed": missed}


# A number with its unit, if any: "35%", "2M", "10x", "4+" ("12 teams"
# doesn't excuse "12%").
_NUMBER_RE = re.compile(r"\d[\d,.]*(?: ?(?:%|[kKmMbB](?![A-Za-z.])|x(?![A-Za-z])|\+))?")


def _norm_number(n: str) -> str:
    n = n.replace(" ", "").replace(",", "").rstrip(".")
    return re.sub(r"(\d)\.0+(?=\D|$)", r"\1", n).upper()


def fabricated_numbers(output_text: str, source_text: str) -> List[str]:
    """Numbers (with their units) in the tailored resume that the original
    doesn't have."""
    source = {_norm_number(n) for n in _NUMBER_RE.findall(source_text or "")}
    return sorted({_norm_number(n) for n in _NUMBER_RE.findall(output_text or "")} - source - {""})


STUFFING_MAX_REPEATS = 5


def stuffing(output_text: str, keywords: List[str], rate_after: float, rate_before: float) -> Dict:
    """Signs of keyword stuffing: tailoring pushed the rate above the target
    band (a resume that already matched that well isn't stuffed), or one JD
    keyword is repeated more than STUFFING_MAX_REPEATS times."""
    from app.domain.report import TARGET_BAND
    repeated = {k: n for k in keywords if (n := JDAnalyzer.count_occurrences(k, output_text or "")) > STUFFING_MAX_REPEATS}
    pushed_over = rate_after > TARGET_BAND[1] and rate_after > rate_before
    return {"pushed_over_band": pushed_over, "repeated": repeated, "ok": not pushed_over and not repeated}


def _docx_text(path: Optional[str]) -> str:
    if not path or not os.path.exists(path):
        return ""
    import docx
    d = docx.Document(path)
    cells = [c.text for t in d.tables for row in t.rows for c in row.cells]
    return "\n".join([p.text for p in d.paragraphs] + cells)


# Messages from check_expected() about what was read or kept, as opposed to
# scoring, page count or output-file checks (P8.1 splits persona results).
CONTENT_CHECKS = ("name", "email", "phone", "jobs", "companies", "roles", "bullets", "projects", "education",
                  "skills", "job ", "must_keep", "coverage")


def is_content_failure(message: str) -> bool:
    return message.startswith(CONTENT_CHECKS)


def _same_text(a: Optional[str], b: Optional[str]) -> bool:
    norm = lambda t: re.sub(r"\s+", " ", (t or "")).strip().lower()
    return norm(a) == norm(b)


def check_job_details(want: List[Dict], experience) -> List[str]:
    """Each job's title, company, dates and bullet count as the file states
    them (P8.1). The company may carry more after it ("Acme, Pune, India"
    for "Acme"); every other field must match."""
    failed: List[str] = []
    for i, (w, exp) in enumerate(zip(want, experience), start=1):
        roles = exp.all_roles()
        first = roles[0] if roles else None
        got = {"title": first.title if first else "", "start": first.start_date if first else None,
               "end": first.end_date if first else None, "bullets": len(exp.bullets)}
        for key in ("title", "start", "end"):
            if key in w and not _same_text(w[key], got[key]):
                failed.append(f"job {i} {key}: expected {w[key]!r}, got {got[key]!r}")
        if "company" in w and not (exp.company or "").lower().startswith(w["company"].lower()):
            failed.append(f"job {i} company: expected {w['company']!r}, got {exp.company!r}")
        if "bullets" in w and w["bullets"] != got["bullets"]:
            failed.append(f"job {i} bullets: expected {w['bullets']}, got {got['bullets']}")
    return failed


def check_must_keep(phrases: List[str], output_text: Optional[str]) -> List[str]:
    """Source phrases that must survive into the rendered file."""
    if output_text is None:
        return [f"must_keep: not checked (run with --tailor): {len(phrases)} phrase(s)"] if phrases else []
    have = re.sub(r"\s+", " ", output_text).lower()
    return [f"must_keep: missing from the output: {p!r}" for p in phrases
            if re.sub(r"\s+", " ", p).lower() not in have]


def check_expected(expected: Dict, resume, job, keyword_report, metrics: Dict,
                   output_text: Optional[str] = None) -> List[str]:
    """Compare a run with the case's expected.json; one message per miss."""
    from app.analysis.experience import target_pages
    from app.rendering.layout import section_order_for

    failed: List[str] = []

    def check(label, want, got):
        if want != got:
            failed.append(f"{label}: expected {want!r}, got {got!r}")

    facts = {
        "name": resume.candidate.name,
        "email": resume.candidate.email,
        "jobs": len(resume.experience),
        "companies": [e.company for e in resume.experience],
        "roles": [[r.title for r in e.all_roles()] for e in resume.experience],
        "bullets": sum(len(e.bullets) for e in resume.experience) + sum(len(p.bullets) for p in resume.projects),
        "projects": len(resume.projects),
        "education": len(resume.education),
        "skills": sorted({s for items in resume.skills.values() for s in items}),
        "target_pages": target_pages(resume),
    }
    for key, got in facts.items():
        if key in expected:
            check(key, expected[key], got)
    if "phone" in expected:
        digits = lambda t: re.sub(r"\D", "", t or "")
        if digits(expected["phone"]) != digits(resume.candidate.phone):
            failed.append(f"phone: expected {expected['phone']!r}, got {resume.candidate.phone!r}")
    if "job_details" in expected:
        failed += check_job_details(expected["job_details"], resume.experience)
    if "must_keep" in expected:
        failed += check_must_keep(expected["must_keep"], output_text)
    if "education_first" in expected:
        order = section_order_for(resume)
        check("education_first", expected["education_first"], order.index("education") < order.index("experience"))
    if "jd_company" in expected:
        check("jd_company", expected["jd_company"], job.company)
    found = {r.keyword.lower() for r in keyword_report.rows if r.found}
    listed = {k.lower() for k in job.keywords}
    for kw in expected.get("must_find", []):
        if kw.lower() not in listed:
            failed.append(f"JD keyword not extracted: {kw}")
        elif kw.lower() not in found:
            failed.append(f"JD keyword not found in the resume: {kw}")
    for kw in expected.get("must_not_be_keywords", []):
        if kw.lower() in listed:
            failed.append(f"boilerplate taken as a JD keyword: {kw}")
    attainable = metrics["match"]["attainable_coverage"]
    if attainable["pct"] is not None and attainable["pct"] < 95.0:
        failed.append(f"attainable keyword coverage {attainable['pct']}% < 95% (missed {attainable['missed']})")
    t = metrics.get("tailor")
    if t:
        if t["pages"] is not None and t["target_pages"] and t["pages"] > t["target_pages"]:
            failed.append(f"{t['pages']} pages, target {t['target_pages']}")
        if t["ats_round_trip"]:
            failed.append(f"ATS round-trip: {t['ats_round_trip'][0]}")
        cov = t.get("coverage") or {}
        if cov.get("lost"):
            failed.append(f"coverage: {len(cov['lost'])} source line(s) lost, e.g. {cov['lost'][0][:80]!r}")
        if t["fabricated_numbers"]:
            failed.append(f"numbers not in the resume: {t['fabricated_numbers']}")
        if not t["stuffing"]["ok"]:
            failed.append(f"keyword stuffing: {t['stuffing']}")
    return failed


def _judge(jd_text: str, original: str, tailored: str) -> Dict:
    """Judge one tailored resume (P4.3) and record what the judge cost."""
    from app.eval.judge import ResumeJudge, judge_client

    client = judge_client()
    result = ResumeJudge(client).judge(jd_text, original, tailored)
    usage = client.get_usage_summary()
    result["judge_calls"], result["judge_tokens"] = usage.get("call_count", 0), usage.get("total_tokens", 0)
    return result


def replay_case(case: Case, replay_dir: str) -> Dict:
    """Judge the tailored output a previous run saved in replay_dir/<case>/
    without generating anything again (P4.3 --replay)."""
    from app.services.tailor import TailorService

    folder = os.path.join(replay_dir, case.name)
    docs = [os.path.join(folder, f) for f in os.listdir(folder)
            if f.endswith(".docx") and not f.startswith("~$")] if os.path.isdir(folder) else []
    if not docs:
        return {"private": case.private, "error": f"no tailored .docx in {folder}"}
    if len(docs) > 1:
        logger.warning("%s: %d tailored files in %s; judging the newest", case.name, len(docs), folder)
    docs = [max(docs, key=os.path.getmtime)]  # a reused --out-dir can hold an older run's file
    with open(case.jd, encoding="utf-8") as f:
        jd_text = f.read()
    raw_doc = TailorService(llm_client=OfflineLLM()).parse_resume(case.resume)[0]
    return {"private": case.private,
            "judge": _judge(jd_text, raw_doc.raw_text, _docx_text(docs[0]))}


def run(cases: List[Case], *, live: bool = False, tailor: bool = False, out_dir: Optional[str] = None,
        judge: bool = False, replay: Optional[str] = None) -> Dict:
    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "mode": f"replay of {replay}" if replay else ("live" if live else "offline"),
        "tailor": tailor,
        "cases": {},
    }
    for case in cases:
        logger.info("Evaluating %s", case.name)
        try:
            if replay:
                report["cases"][case.name] = replay_case(case, replay)
                continue
            report["cases"][case.name] = run_case(case, live=live, tailor=tailor, out_dir=out_dir, judge=judge)
        except Exception as e:  # one broken case shouldn't hide the others
            report["cases"][case.name] = {"private": case.private, "error": f"{type(e).__name__}: {e}"}
    return report


def _flatten(d: Dict, prefix: str = "") -> Dict[str, object]:
    flat: Dict[str, object] = {}
    for key, value in d.items():
        path = f"{prefix}{key}"
        if isinstance(value, dict):
            flat.update(_flatten(value, path + "."))
        else:
            flat[path] = value
    return flat


# Metrics where a lower number is better; everything else numeric is
# reported as a plain delta.
LOWER_IS_BETTER = ("llm.calls", "llm.tokens", "llm.llm_seconds", "llm.retries_429", "llm.failures",
                   "elapsed_s", "tailor.pages", "statuses.MISSING", "verdicts.REJECT", "parse.issues")


def compare(report: Dict, baseline: Dict) -> List[str]:
    """Human-readable differences per case between a report and a baseline."""
    lines: List[str] = []
    for name, metrics in report.get("cases", {}).items():
        base = baseline.get("cases", {}).get(name)
        if base is None:
            lines.append(f"{name}: new case (no baseline)")
            continue
        now_flat, base_flat = _flatten(metrics), _flatten(base)
        changes = []
        for key in sorted(set(now_flat) | set(base_flat)):
            if key.endswith(("output_dir", "missing", "keywords_missing", "golden_mismatches")) or key == "elapsed_s":
                continue
            old, new = base_flat.get(key), now_flat.get(key)
            if old == new:
                continue
            if isinstance(old, (int, float)) and isinstance(new, (int, float)) and not isinstance(old, bool):
                delta = new - old
                better = (delta < 0) if any(key.endswith(k) for k in LOWER_IS_BETTER) else (delta > 0)
                mark = "↑" if delta > 0 else "↓"
                changes.append(f"  {key}: {old} → {new} ({mark}{abs(round(delta, 1))}{'' if better else ' ⚠'})")
            else:
                changes.append(f"  {key}: {old!r} → {new!r}")
        lines.append(f"{name}: " + ("no change" if not changes else f"{len(changes)} change(s)"))
        lines.extend(changes)
    return lines


def _judge_summary(j: Dict) -> str:
    overall = (j.get("rubric") or {}).get("overall", "error")
    verdict = (j.get("pairwise") or {}).get("verdict", "error")
    return f"judge overall={overall}/5, pairwise={verdict}, {j.get('judge_tokens', 0)} tok"


def summary_lines(report: Dict) -> List[str]:
    lines = [f"Evaluation ({report['mode']}{', tailor' if report.get('tailor') else ''}) at {report['generated_at']}"]
    for name, m in report["cases"].items():
        if "error" in m:
            lines.append(f"- {name}: ERROR {m['error']}")
            continue
        if "judge" in m and "match" not in m:  # replay: judge only
            lines.append(f"- {name}: {_judge_summary(m['judge'])}")
            continue
        kc = m["match"]["keyword_coverage"]
        parts = [
            f"parse={m['parse'].get('golden', 'n/a')}",
            f"jd={m['jd']['requirements']} req/{m['jd']['preferred']} pref ({m['jd']['source']})",
            f"score={m['match']['score']}",
            f"keywords={kc['found']}/{kc['total']}",
        ]
        if "tailor" in m:
            t = m["tailor"]
            parts += [f"rewrites={t['changed']}/{t['proposals']}", f"pages={t['pages']}"]
        if (m.get("tailor") or {}).get("judge"):
            parts.append(_judge_summary(m["tailor"]["judge"]))
        if "expected" in m:
            parts.append("expected=ok" if m["expected"]["ok"] else f"expected=FAILED({len(m['expected']['failed'])})")
        parts.append(f"llm={m['llm']['calls']} calls/{m['llm']['tokens']} tok/{m['llm']['retries_429']}×429")
        lines.append(f"- {name}: " + ", ".join(parts))
    return lines
